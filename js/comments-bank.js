  /**
   * Suggest an appropriate comment based on numeric score
   */
  suggestComment(score) {
    if (score >= 9.0) {
      return this.categories.excellent[0];
    } else if (score >= 8.0) {
      return this.categories.good[0];
    } else if (score >= 7.0) {
      return this.categories.fair[0];
    } else {
      return this.categories.needsImprovement[0];
    }
  },

  /**
   * Format bilingual text
   */
  formatBilingual(commentItem) {
    if (!commentItem) return '';
    return `${commentItem.textKm} / ${commentItem.textCn}`;
  }
